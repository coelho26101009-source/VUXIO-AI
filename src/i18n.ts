type Key = keyof typeof dict.pt;

/** `t('app.rememberSaved', { value })` -- `{name}` placeholders in the string
 *  are replaced from `vars`. Falls back to the raw key if a translation is
 *  ever missing (should not happen: both locales are written together above). */
export const t = (key: Key, vars?: Record<string, string | number>): string => {
  let str: string = dict[getLocale()][key] ?? dict.pt[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) str = str.replaceAll(`{${name}}`, String(value));
  return str;
};
