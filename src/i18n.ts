export type Locale = 'pt' | 'en';

/**
 * Reads `navigator.languages` (falls back to `navigator.language`) and picks
 * 'pt' if any preferred language is Portuguese, else 'en'. English is the
 * fallback for every other locale rather than trying to ship a translation
 * per language -- the AI Act / GDPR disclosures and the model's own replies
 * already handle arbitrary languages (see LANGUAGE_RULE in api/chat.js);
 * this only covers the static UI chrome around them.
 */
export const detectLocale = (): Locale => {
  const prefs = navigator.languages?.length ? navigator.languages : [navigator.language];
  return prefs.some(lang => lang.toLowerCase().startsWith('pt')) ? 'pt' : 'en';
};

// Locale never changes mid-session (no manual switcher exists), so this is a
// plain cached value, not React state -- no context/provider needed for a
// value nothing re-renders on.
let cached: Locale | null = null;
export const getLocale = (): Locale => cached ?? (cached = detectLocale());

